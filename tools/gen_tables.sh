#!/bin/sh
# Generate syscall and errno tables from the host's kernel/libc headers.
# Usage: gen_tables.sh OUTPUT_FILE
set -eu

CC=${CC:-gcc}
out=${1:?usage: gen_tables.sh OUTPUT_FILE}
tmp="$out.tmp"

sys_defs=$($CC -E -dM -include sys/syscall.h -x c /dev/null)
err_defs=$($CC -E -dM -include errno.h -x c /dev/null)

{
    echo "/* Generated by tools/gen_tables.sh from the host headers. Do not edit. */"
    echo
    echo "static const struct { long nr; const char *name; } syscall_list[] = {"
    printf '%s\n' "$sys_defs" | awk '
        $1 == "#define" && $2 ~ /^__NR_[a-z0-9_]+$/ &&
        $2 != "__NR_syscalls" && $3 ~ /^[0-9]+$/ {
            n = substr($2, 6)
            printf "    { __NR_%s, \"%s\" },\n", n, n
        }' | LC_ALL=C sort
    echo "};"
    echo
    echo "static const char *const errno_list[] = {"
    # Only numeric definitions: aliases such as EWOULDBLOCK expand to another
    # macro name and are skipped, so every errno value has a single name.
    printf '%s\n' "$err_defs" | awk '
        $1 == "#define" && $2 ~ /^E[A-Z0-9]+$/ && $3 ~ /^[0-9]+$/ &&
        $2 != "EWOULDBLOCK" && $2 != "EDEADLOCK" && $2 != "ENOTSUP" {
            printf "    [%s] = \"%s\",\n", $2, $2
        }' | LC_ALL=C sort
    echo "};"
} > "$tmp"

if ! grep -q '__NR_read' "$tmp" || ! grep -q '\[ENOENT\]' "$tmp"; then
    echo "gen_tables.sh: could not extract tables from headers" >&2
    rm -f "$tmp"
    exit 1
fi

mv "$tmp" "$out"